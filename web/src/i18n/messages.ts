export function readUiLocale(get: (key: string) => string | null): UiLocale {
  const v = get(UI_KEY);
  return v === "en" || v === "vi" ? v : "vi";
}

export function writeUiLocale(
  set: (key: string, value: string) => void,
  locale: UiLocale,
) {
  set(UI_KEY, locale);
}
