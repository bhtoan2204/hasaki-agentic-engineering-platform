import { test } from "node:test";
import assert from "node:assert/strict";
import { mkdtempSync, mkdirSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { execFileSync } from "node:child_process";
import { ocrBinary, openCodeReviewGuide, parsePreview } from "../src/agent/openCodeReview.ts";

test("parsePreview keeps reviewable files and drops the ones OCR struck out", () => {
  const out = [
    "# Files (2 reviewable / 3 total)",
    "~~- `proto/oms/oms.pb.go` [modified] +1411/-648 (excluded: default_path)~~",
    "  - `application/handler/list_audit_log.go` [added] +84/-0",
    "  - `proto/oms/oms.proto` [modified] +72/-0",
  ].join("\n");
  assert.deepEqual(parsePreview(out), ["application/handler/list_audit_log.go", "proto/oms/oms.proto"]);
});

test("openCodeReviewGuide: real ocr on a branch — generated code excluded, Go rules resolved, no LLM needed", { skip: !ocrBinary() && "ocr not installed" }, async () => {
  const root = mkdtempSync(join(tmpdir(), "ocr-"));
  const g = (cwd: string, ...a: string[]) => execFileSync("git", ["-C", cwd, ...a], { stdio: "pipe" }).toString();
  const origin = join(root, "origin.git"), repo = join(root, "svc");
  execFileSync("git", ["init", "-q", "--bare", "-b", "release/prod", origin]);
  execFileSync("git", ["init", "-q", "-b", "release/prod", repo]);
  g(repo, "config", "user.email", "t@t"); g(repo, "config", "user.name", "t");
  writeFileSync(join(repo, "go.mod"), "module example.com/svc\n\ngo 1.22\n");
  g(repo, "add", "."); g(repo, "commit", "-qm", "base");
  g(repo, "remote", "add", "origin", origin); g(repo, "push", "-q", "origin", "release/prod");
  g(repo, "switch", "-qc", "feature");
  mkdirSync(join(repo, "pkg"), { recursive: true });
  writeFileSync(join(repo, "pkg", "handler.go"), "package pkg\n\nimport \"os\"\n\nfunc Read(p string) []byte {\n\tb, _ := os.ReadFile(p)\n\treturn b\n}\n");
  writeFileSync(join(repo, "pkg", "api.pb.go"), "// Code generated by protoc-gen-go. DO NOT EDIT.\npackage pkg\n");
  g(repo, "add", "."); g(repo, "commit", "-qm", "feature");

  const guide = await openCodeReviewGuide([{ repo: "svc", path: repo }], "release/prod");
  assert.equal(guide.available, true);
  assert.deepEqual(guide.repos, [{ repo: "svc", files: 1 }], "only handler.go is reviewable");
  assert.match(guide.text, /pkg\/handler\.go/);
  assert.match(guide.text, /~~- `pkg\/api\.pb\.go`/, "generated file listed as excluded");
  assert.match(guide.text, /Go Review Principles/, "per-language rules resolved");
});

test("openCodeReviewGuide on a main checkout reviews origin/<branch> without touching the working tree", { skip: !ocrBinary() && "ocr not installed" }, async () => {
  const root = mkdtempSync(join(tmpdir(), "ocr-main-"));
  const g = (cwd: string, ...a: string[]) => execFileSync("git", ["-C", cwd, ...a], { stdio: "pipe" }).toString();
  const origin = join(root, "origin.git"), repo = join(root, "svc");
  execFileSync("git", ["init", "-q", "--bare", "-b", "release/prod", origin]);
  execFileSync("git", ["init", "-q", "-b", "release/prod", repo]);
  g(repo, "config", "user.email", "t@t"); g(repo, "config", "user.name", "t");
  writeFileSync(join(repo, "go.mod"), "module example.com/svc\n\ngo 1.22\n");
  g(repo, "add", "."); g(repo, "commit", "-qm", "base");
  g(repo, "remote", "add", "origin", origin); g(repo, "push", "-q", "origin", "release/prod");
  g(repo, "switch", "-qc", "HSK-1");
  writeFileSync(join(repo, "audit.go"), "package svc\n\nfunc Record() {}\n");
  g(repo, "add", "."); g(repo, "commit", "-qm", "audit"); g(repo, "push", "-q", "origin", "HSK-1");
  g(repo, "switch", "-q", "release/prod"); // the developer's checkout is elsewhere
  g(repo, "fetch", "-q", "origin");

  const guide = await openCodeReviewGuide([{ repo: "svc", path: repo, to: "origin/HSK-1" }], "release/prod");
  assert.deepEqual(guide.repos, [{ repo: "svc", files: 1 }]);
  assert.match(guide.text, /audit\.go/);
  assert.equal(g(repo, "rev-parse", "--abbrev-ref", "HEAD").trim(), "release/prod", "checkout untouched");
  assert.equal(g(repo, "status", "--porcelain").trim(), "", "no files written into the repository");
});
